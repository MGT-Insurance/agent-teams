// ---- routing fields cross the Go/TS boundary (agent-teams-ully.12) ----------
//
// The rule that turns description text into routing fields now lives in exactly
// one place: Go's internal/initiative. This file used to hold a second
// implementation of it (parseDescriptionFields) plus ~14 tests pinning the rule
// itself; both are gone. Those rule assertions did not evaporate, they moved to
// where the rule is — internal/initiative/jsonfields_test.go and
// initiative_test.go, including TestJSONFieldsRejectsNearMissFieldLines for the
// colon/space/column-0 near-misses this file used to own.
//
// What TypeScript still has to prove is the half Go cannot: that the JSON the
// verb actually emits feeds this consumer correctly. The fixture below is not
// hand-written — it is testdata/list-json/ateam-list-json.golden.json, produced
// by `ateam list-json` itself over five real registry records (see
// internal/verbs/listjson_golden_test.go). One artifact, two languages: change
// the Go output shape and the Go test fails until the golden is regenerated,
// and the regenerated golden is what these tests then read. Two hand-maintained
// fixture sets, one per language, would be the same drift this initiative exists
// to remove.
//
// If this file cannot find the golden, the repo layout moved: regenerate with
//   go test ./internal/verbs/ -run TestListJSONGolden -update

