// ---- epic resolution --------------------------------------------------------
//
// `epic` is a routing field, so the description half now arrives pre-parsed in
// `fields.epic` (agent-teams-ully.12) and is asserted through parseInitiative
// below. extractEpicFromNotes is the surviving legacy fallback and reads NOTES
// only — notes are not routing data, so internal/initiative never looks at them
// and `fields` can never carry this case.

describe("extractEpicFromNotes", () => {
  it("returns the epic id from notes", () => {
    expect(extractEpicFromNotes("session 1\nepic: agent-teams-abcd\ndone")).toBe("agent-teams-abcd");
  });

  it("returns null when notes has no epic: line", () => {
    expect(extractEpicFromNotes("session 1")).toBeNull();
  });

  it("returns null for an empty string", () => {
    expect(extractEpicFromNotes("")).toBeNull();
  });

  it("does not look at description text — a description-only epic is fields.epic's job", () => {
    expect(extractEpicFromNotes("")).toBeNull();
    const parsed = parseInitiative({
      ...RAW_AT_V4E,
      description: "repo: /r\nepic: agent-teams-x6ce\n",
      notes: "",
      fields: { repo: "/r", epic: "agent-teams-x6ce" },
    });
    expect(parsed.epic).toBe("agent-teams-x6ce");
  });
});

